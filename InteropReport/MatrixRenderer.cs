using System.Text;

using PKIConformance.Core;

namespace PKIConformance.InteropReport;

/// <summary>
/// The interop results as <c>docs/INTEROP-MATRIX.md</c>: a table per matrix,
/// its rows the cells of <see cref="InteropCells"/> in their order, its
/// columns the peers with their versions; then every red test and what keeps
/// it red.
/// </summary>
/// <remarks>
/// A red cell is a finding or a ToDo until shown otherwise: a red test
/// without either is "unexplained", said so at the top, and the report's
/// exit code says it too. A test that did not run is no evidence either way,
/// and is marked as such - never as green.
/// </remarks>
public static class MatrixRenderer
{

    private sealed record Matrix(String Id, String Title, String Columns, IReadOnlyList<String> Rows);

    private static readonly Matrix[] matrices = [
        new (InteropCells.Clients,   "Real clients against the PKI",            "PLAN.md, section 4.5", InteropCells.ClientRows),
        new (InteropCells.Servers,   "Hermod against real servers",             "PLAN.md, section 4.6", InteropCells.ServerRows),
        new (InteropCells.Reference, "The reference run: certbot's own files",  "PLAN.md, section 4.6", InteropCells.ReferenceRows)
    ];

    /// <summary>
    /// The report of the results.
    /// </summary>
    /// <param name="Results">The interop results.</param>
    /// <param name="Started">When the earliest run of them began.</param>
    public static String Render(IReadOnlyList<Result> Results, DateTimeOffset? Started)
    {

        var report      = new StringBuilder();
        var passed      = Results.Count(result => result.Outcome == Outcome.Passed);
        var failed      = Results.Count(result => result.Outcome == Outcome.Failed);
        var notRun      = Results.Count(result => result.Outcome == Outcome.NotRun);
        var unexplained = Unexplained(Results);
        var against     = Results.Where (result => result.Matrix is not null && result.Against != "?").
                                  Select(result => result.Against).
                                  Distinct().
                                  Order(StringComparer.Ordinal).
                                  ToArray();

        report.AppendLine("# PKI ACME interoperability matrix");
        report.AppendLine();
        report.AppendLine("Generated by `InteropReport` from the TRX files of one interop run - do not edit by hand:");
        report.AppendLine();
        report.AppendLine("```");
        report.AppendLine("dotnet run --project InteropReport -- <the run's TRX files or their directory>");
        report.AppendLine("```");
        report.AppendLine();
        report.AppendLine((Started is not null ? $"Run of {Started.Value.UtcDateTime:yyyy-MM-dd HH:mm} UTC" : "A run") +
                          (against.Length > 0 ? $", against {String.Join(" and ", against)}." : "."));
        report.AppendLine();
        report.AppendLine($"**{passed} passed · {failed} failed · {notRun} not run** of {Results.Count} interop tests.");
        report.AppendLine();

        if (Results.Count == 0)
            report.AppendLine("> ⚪ No interop results: none of the TRX files is of a run of the interop tests.");
        else if (unexplained.Count > 0)
            report.AppendLine($"> ❌ {unexplained.Count} red test(s) without a finding or a ToDo - see \"Red, and why\".");
        else if (failed > 0)
            report.AppendLine("> Every red test is a finding or a ToDo (FINDINGS.md, PLAN.md section 2.4).");
        else
            report.AppendLine("> Every test that ran passed.");

        if (notRun > 0)
            report.AppendLine($"> ⚪ {notRun} test(s) did not run: no evidence either way.");

        report.AppendLine();

        foreach (var matrix in matrices)
            AppendMatrix(report, matrix, Results.Where(result => result.Matrix == matrix.Id).ToArray());

        AppendBench (report, Results.Where(result => result.Matrix == InteropCells.Bench).ToArray());
        AppendOthers(report, Results.Where(result => result.Matrix is null || !matrices.Any(matrix => matrix.Id == result.Matrix) && result.Matrix != InteropCells.Bench).ToArray());
        AppendRed   (report, Results);
        AppendLegend(report);

        return report.ToString();

    }

    /// <summary>The red tests that have neither a finding nor a ToDo.</summary>
    public static IReadOnlyList<Result> Unexplained(IReadOnlyList<Result> Results)
        => Results.Where(result => result.Outcome == Outcome.Failed && result.Reason is null).ToArray();


    private static void AppendMatrix(StringBuilder Report, Matrix Matrix, Result[] Results)
    {

        if (Results.Length == 0)
            return;

        var peers = Results.Select(result => result.Peer).Distinct().Order(StringComparer.OrdinalIgnoreCase).ToArray();
        var rows  = Matrix.Rows.Concat(Results.Select(result => result.Cell).Where(cell => !Matrix.Rows.Contains(cell)).Distinct()).ToArray();

        Report.AppendLine($"## {Matrix.Title}");
        Report.AppendLine();
        Report.AppendLine($"{Results.Length} tests; the rows as in {Matrix.Columns}.");
        Report.AppendLine();
        Report.AppendLine("| Cell | " + String.Join(" | ", peers) + " |");
        Report.AppendLine("|---|" + String.Join("|", peers.Select(_ => "---")) + "|");

        foreach (var row in rows)
        {
            var known = Matrix.Rows.Contains(row) ? row : $"{row} *(not in InteropCells)*";
            Report.AppendLine($"| {known} | " + String.Join(" | ", peers.Select(peer => Cell(Results.Where(result => result.Peer == peer && result.Cell == row).ToArray()))) + " |");
        }

        Report.AppendLine();

    }

    private static String Cell(Result[] Results)
    {

        if (Results.Length == 0)
            return "–";

        var parts  = new List<String>();
        var passed = Results.Count(result => result.Outcome == Outcome.Passed);
        var notRun = Results.Count(result => result.Outcome == Outcome.NotRun);

        if (passed > 0)
            parts.Add(passed == 1 ? "✅" : $"✅ {passed}");

        foreach (var red in Results.Where(result => result.Outcome == Outcome.Failed).GroupBy(result => result.Reason ?? "?"))
            parts.Add(red.Count() == 1 ? $"❌ {red.Key}" : $"❌ {red.Key} ×{red.Count()}");

        if (notRun > 0)
            parts.Add(notRun == 1 ? "⚪" : $"⚪ {notRun}");

        return String.Join(" ", parts);

    }

    private static void AppendBench(StringBuilder Report, Result[] Results)
    {

        if (Results.Length == 0)
            return;

        Report.AppendLine("## The bench itself");
        Report.AppendLine();
        Report.AppendLine("Tested before it judges anything: the names resolve, BIND and challtestsrv answer, the servers start, the judge of the wire finds what it is to find.");
        Report.AppendLine();
        Report.AppendLine("| Bench | Tests |");
        Report.AppendLine("|---|---|");

        foreach (var bench in Results.GroupBy(result => result.Peer).OrderBy(group => group.Key, StringComparer.Ordinal))
            Report.AppendLine($"| {bench.Key} | {Cell([ .. bench ])} |");

        Report.AppendLine();

    }

    private static void AppendOthers(StringBuilder Report, Result[] Results)
    {

        if (Results.Length == 0)
            return;

        Report.AppendLine("## Not attributed");
        Report.AppendLine();
        Report.AppendLine("Interop tests that wrote no line of their cell - a fixture that skipped before its SetUp - or of a matrix this report does not know.");
        Report.AppendLine();

        foreach (var result in Results.OrderBy(result => result.Test, StringComparer.Ordinal))
            Report.AppendLine($"- {Mark(result.Outcome)} `{result.Test}`" + (result.Message is not null ? $" - {result.Message}" : ""));

        Report.AppendLine();

    }

    private static void AppendRed(StringBuilder Report, IReadOnlyList<Result> Results)
    {

        var red = Results.Where(result => result.Outcome == Outcome.Failed).
                          OrderBy(result => result.Reason is null ? 0 : 1).
                          ThenBy (result => result.Reason, StringComparer.Ordinal).
                          ThenBy (result => result.Peer,   StringComparer.OrdinalIgnoreCase).
                          ThenBy (result => result.Test,   StringComparer.Ordinal).
                          ToArray();

        if (red.Length == 0)
            return;

        Report.AppendLine("## Red, and why");
        Report.AppendLine();

        foreach (var result in red)
            Report.AppendLine($"- ❌ **{result.Reason ?? "unexplained"}** - {result.Peer} - `{result.Test}`" +
                              (result.Reason is null && result.Message is not null ? $" - {result.Message}" : ""));

        Report.AppendLine();

    }

    private static void AppendLegend(StringBuilder Report)
    {
        Report.AppendLine("## Legend");
        Report.AppendLine();
        Report.AppendLine("| Mark | Meaning |");
        Report.AppendLine("|---|---|");
        Report.AppendLine("| ✅ *n* | *n* tests of the cell passed. |");
        Report.AppendLine("| ❌ *X-n* | A test of the cell failed, at the finding (FINDINGS.md) or the ToDo (PLAN.md, section 2.4) it names. |");
        Report.AppendLine("| ❌ ? | A test failed without a finding or a ToDo: unexplained, to be triaged. |");
        Report.AppendLine("| ⚪ *n* | *n* tests did not run - a peer or a tool was missing: no evidence either way. |");
        Report.AppendLine("| – | No test: the peer lacks the feature (PLAN.md, principle 7), or the cell is not built yet - PLAN.md, sections 4.5 and 4.6, say which. |");
    }

    private static String Mark(Outcome Outcome)
        => Outcome switch {
               Outcome.Passed => "✅",
               Outcome.Failed => "❌",
               _              => "⚪"
           };

}
